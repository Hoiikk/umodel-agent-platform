#!/bin/sh
set -eu
mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" "${MYSQL_DATABASE}" <<SQL
CREATE USER IF NOT EXISTS '${RMS_DB_USER}'@'%' IDENTIFIED BY '${RMS_DB_PASSWORD}';
GRANT SELECT, INSERT, UPDATE ON \`${MYSQL_DATABASE}\`.* TO '${RMS_DB_USER}'@'%';
CREATE USER IF NOT EXISTS '${RMS_READONLY_USER}'@'%' IDENTIFIED BY '${RMS_READONLY_PASSWORD}';
GRANT SELECT ON \`${MYSQL_DATABASE}\`.* TO '${RMS_READONLY_USER}'@'%';
FLUSH PRIVILEGES;
SQL
